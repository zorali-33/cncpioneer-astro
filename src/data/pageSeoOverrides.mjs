export function getReviewedSeo(canonical) {
  if (!canonical) return {};
  const route = new URL(canonical, "https://www.cncpioneer.com").pathname.replace(/\/+$/, "") || "/";
  const edit = pageSeoOverrides[route];
  if (!edit) return {};
  return { ...edit, ...(edit.description ? { ogDescription: edit.description, includeDescription: true } : {}) };
}

const escapeHtml = (value) => String(value).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

// The mirrored archive head may lack description tags or contain a revised title.
// Match tag identity, not the old title text, and insert missing tags exactly once.
export function applyArchiveMetadata(html, { title, description }) {
  if (title) html = html.replace(/<title[^>]*>[\s\S]*?<\/title>/i, () => `<title>${escapeHtml(title)}</title>`);
  for (const [attribute, key, value] of [["property", "og:title", title], ["name", "description", description], ["property", "og:description", description]]) {
    if (!value) continue;
    const pattern = new RegExp(`<meta\\b(?=[^>]*\\b${attribute}=["']${key}["'])[^>]*>\\s*`, "gi");
    html = html.replace(pattern, "").replace(/<\/head>/i, () => `<meta ${attribute}="${key}" content="${escapeHtml(value)}" />\n</head>`);
  }
  return html;
}
