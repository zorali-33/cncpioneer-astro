import assert from "node:assert/strict";
import { createQuoteMeasurement } from "../src/lib/quoteMeasurement.mjs";
const events = [];
let agreed = true;
const transport = (...args) => events.push(args);
const tracker = createQuoteMeasurement({ enabled: true, consent: () => agreed, transport });
const context = { page_path: "/custom-cnc-parts/heat-sinks?email=private@example.com#secret", cta_location: "hero", part_category: "product", email: "private@example.com", filename: "drawing.step" };
assert.equal(tracker.emit("quote_cta_click", context), true);
assert.equal(events[0][0], "quote_cta_click");
assert.equal(tracker.emit("quote_form_start", context), true);
assert.equal(tracker.emit("quote_form_start", context), false);
assert.equal(tracker.emit("quote_submit_success", context), false);
assert.equal(tracker.emit("quote_submit_success", context, { confirmed: false, id: "failed" }), false);
assert.equal(tracker.emit("quote_submit_success", context, { confirmed: true, id: "server-1" }), true);
assert.equal(tracker.emit("quote_submit_success", context, { confirmed: true, id: "server-1" }), false);
assert.equal(tracker.emit("drawing_upload_success", context, { confirmed: false, id: "upload-failed" }), false);
assert.equal(tracker.emit("drawing_upload_success", context, { confirmed: true, id: "upload-1" }), true);
assert.equal(tracker.emit("drawing_upload_success", context, { confirmed: true, id: "upload-1" }), false);
agreed = false;
assert.equal(tracker.emit("quote_cta_click", context), false);
assert.equal(createQuoteMeasurement({ transport, consent: () => true }).emit("quote_cta_click", context), false);
assert.equal(createQuoteMeasurement({ enabled: true, consent: () => true }).emit("quote_cta_click", context), false);
assert(!JSON.stringify(events).match(/private|drawing\.step|secret|server-1|upload-1/));
assert.equal(events.length, 4);
console.log("PASS: click/start, confirmed success, failures, deduplication, privacy, no consent and disabled transport; no network requests.");
